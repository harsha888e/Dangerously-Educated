export function getDeckQuestions(selection: CategoryId | 'all'): TriviaQuestion[] {
  if (selection === 'all') return [...QUESTIONS];
  return QUESTIONS.filter((q) => q.category === selection);
}

export function getCategoryLabel(category: CategoryId): string {
  switch (category) {
    case 'movies':
      return 'Movies';
    case 'games':
      return 'Games';
    case 'cars':
      return 'Cars';
    case 'everything':
      return 'General';
    case 'maths':
      return 'Maths';
    case 'aptitude':
      return 'Aptitude';
  }
}
